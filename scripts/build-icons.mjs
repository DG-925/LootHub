// Builds app/js/brand-icons.js (store logos) and copies Font Awesome into app/vendor.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const nm = p => path.join(root, 'node_modules', p);

// platform key -> [library, file]
const MAP = {
  steam: ['si', 'steam'], epic: ['si', 'epicgames'], gog: ['si', 'gogdotcom'], ubi: ['si', 'ubisoft'],
  ea: ['si', 'ea'], bnet: ['si', 'battledotnet'], ms: ['fa', 'microsoft'], itch: ['si', 'itchdotio'],
  amz: ['fa', 'amazon'], humble: ['si', 'humblebundle'], riot: ['si', 'riotgames'], rock: ['si', 'rockstargames'],
  gj: ['si', 'gamejolt'], discord: ['si', 'discord'], twitch: ['si', 'twitch'], xbox: ['fa', 'xbox'],
  playstation: ['si', 'playstation'], android: ['si', 'android'], apple: ['si', 'apple']
};
const out = {};
for (const [key, [lib, file]] of Object.entries(MAP)) {
  const f = lib === 'si' ? nm(`simple-icons/icons/${file}.svg`) : nm(`@fortawesome/fontawesome-free/svgs/brands/${file}.svg`);
  const svg = fs.readFileSync(f, 'utf8');
  const viewBox = (svg.match(/viewBox="([^"]+)"/) || [, '0 0 24 24'])[1];
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map(m => m[1]).join(' ');
  out[key] = { viewBox, d };
}
fs.writeFileSync(path.join(root, 'app/js/brand-icons.js'),
  '// Generated by scripts/build-icons.mjs from simple-icons (CC0) and Font Awesome Free brands (CC BY 4.0). Do not edit.\n' +
  'export const BRAND_ICONS = ' + JSON.stringify(out) + ';\n');

const faSrc = nm('@fortawesome/fontawesome-free');
const faDst = path.join(root, 'app/vendor/fontawesome');
fs.mkdirSync(path.join(faDst, 'css'), { recursive: true });
fs.mkdirSync(path.join(faDst, 'webfonts'), { recursive: true });
fs.copyFileSync(path.join(faSrc, 'css/all.min.css'), path.join(faDst, 'css/all.min.css'));
for (const w of fs.readdirSync(path.join(faSrc, 'webfonts'))) if (w.endsWith('.woff2'))
  fs.copyFileSync(path.join(faSrc, 'webfonts', w), path.join(faDst, 'webfonts', w));
fs.copyFileSync(path.join(faSrc, 'LICENSE.txt'), path.join(faDst, 'LICENSE.txt'));
console.log('icons:', Object.keys(out).length, 'brand logos; Font Awesome copied');
